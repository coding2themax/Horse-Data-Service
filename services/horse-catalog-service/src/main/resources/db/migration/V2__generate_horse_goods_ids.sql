-- Let PostgreSQL assign goods ids, continuing after any existing rows.
ALTER TABLE stable.horse_goods ALTER COLUMN goods_id TYPE INTEGER;
ALTER TABLE stable.horse_goods ALTER COLUMN goods_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(
  pg_get_serial_sequence('stable.horse_goods', 'goods_id'),
  COALESCE(MAX(goods_id), 0) + 1,
  false
) FROM stable.horse_goods;
